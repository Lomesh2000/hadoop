def output_directory(job):
    mapping = {
        "Q1": "q1_daily_traffic",
        "Q2": "q2_top_resources",
        "Q3": "q3_hourly_errors",
    }

    return OUTPUT_MR / mapping[job]


def read_job_output(job, top_n):
    """
    Read ALL part-* files generated by the MapReduce job.

    Important for Q1/Q3 when multiple reducers are used.
    """

    folder = output_directory(job)

    if not folder.exists():
        return None

    part_files = sorted(
        path
        for path in folder.glob("part-*")
        if path.is_file()
    )

    if not part_files:
        return None

    frames = []

    for path in part_files:
        try:
            df = pd.read_csv(
                path,
                sep="\t",
                header=None,
                engine="python",
            )

            if not df.empty:
                frames.append(df)

        except Exception as exc:
            st.warning(
                f"Could not read {path.name}: {exc}"
            )

    if not frames:
        return None

    df = pd.concat(
        frames,
        ignore_index=True,
    )

    # --------------------------------------------------------
    # Q1
    # --------------------------------------------------------

    if job == "Q1":

        if len(df.columns) == 3:
            df.columns = [
                "Date",
                "Requests",
                "Bytes",
            ]

        df["Date"] = pd.to_datetime(
            df["Date"],
            errors="coerce",
        )

        df["Requests"] = pd.to_numeric(
            df["Requests"],
            errors="coerce",
        )

        df["Bytes"] = pd.to_numeric(
            df["Bytes"],
            errors="coerce",
        )

        df = (
            df.dropna(subset=["Date"])
            .sort_values("Date")
            .reset_index(drop=True)
        )

    # --------------------------------------------------------
    # Q2
    # --------------------------------------------------------

    elif job == "Q2":

        if len(df.columns) == 4:
            df.columns = [
                "Resource",
                "Requests",
                "Bytes",
                "Distinct Hosts",
            ]

        elif len(df.columns) == 3:
            df.columns = [
                "Resource",
                "Requests",
                "Bytes",
            ]

        df["Requests"] = pd.to_numeric(
            df["Requests"],
            errors="coerce",
        )

        df["Bytes"] = pd.to_numeric(
            df["Bytes"],
            errors="coerce",
        )

        df = (
            df.dropna(subset=["Resource", "Requests"])
            .sort_values(
                "Requests",
                ascending=False,
            )
            .head(top_n)
            .reset_index(drop=True)
        )

        df.insert(
            0,
            "Rank",
            range(1, len(df) + 1),
        )

    # --------------------------------------------------------
    # Q3
    # --------------------------------------------------------

    elif job == "Q3":

        if len(df.columns) == 5:
            df.columns = [
                "Hour",
                "Total Requests",
                "Error Requests",
                "Error Rate %",
                "Distinct Error Hosts",
            ]

        elif len(df.columns) == 4:
            df.columns = [
                "Hour",
                "Total Requests",
                "Error Requests",
                "Error Rate %",
            ]

        df["Hour"] = pd.to_datetime(
            df["Hour"],
            errors="coerce",
        )

        for col in [
            "Total Requests",
            "Error Requests",
            "Error Rate %",
        ]:
            df[col] = pd.to_numeric(
                df[col],
                errors="coerce",
            )

        df = (
            df.dropna(subset=["Hour"])
            .sort_values("Hour")
            .reset_index(drop=True)
        )

    return df


