def parse_time(line):
    match = re.search(r"Time:\s*([\d.]+)s", line)
    return float(match.group(1)) if match else None


def parse_total_time(line):
    match = re.search(
        r"COMPLETED SUCCESSFULLY IN\s*([\d.]+)s",
        line,
    )
    return float(match.group(1)) if match else None


def parse_int(line, pattern):
    match = re.search(pattern, line)
    if not match:
        return None

    try:
        return int(match.group(1).replace(",", ""))
    except (ValueError, TypeError):
        return None


