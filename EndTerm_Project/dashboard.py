def load_reducer_config():
    defaults = {
        "q1": 1,
        "q2": 1,
        "q3": 1,
    }

    if not CONFIG_FILE.exists():
        return defaults

    try:
        with CONFIG_FILE.open("r") as f:
            cfg = yaml.safe_load(f) or {}

        hadoop_cfg = cfg.get("hadoop", {})

        return {
            "q1": int(hadoop_cfg.get("num_reducers_q1", 1)),
            "q2": int(hadoop_cfg.get("num_reducers_q2", 1)),
            "q3": int(hadoop_cfg.get("num_reducers_q3", 1)),
        }

    except Exception:
        return defaults


