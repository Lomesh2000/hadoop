def render_q1(df):
    st.markdown("## 📊 Q1 — Daily Traffic")

    if df is None or df.empty:
        st.warning("Q1 completed but produced no rows.")
        return

    total_requests = int(
        df["Requests"].sum()
    )

    total_bytes = int(
        df["Bytes"].sum()
    )

    c1, c2, c3 = st.columns(3)

    c1.metric(
        "Days",
        f"{len(df):,}",
    )

    c2.metric(
        "Total Requests",
        f"{total_requests:,}",
    )

    c3.metric(
        "Total Volume",
        f"{total_bytes / (1024 ** 2):,.2f} MB",
    )

    st.dataframe(
        df,
        use_container_width=True,
        hide_index=True,
    )

    fig = px.line(
        df,
        x="Date",
        y="Requests",
        markers=True,
        title="Daily Request Volume",
    )

    st.plotly_chart(
        fig,
        use_container_width=True,
    )


