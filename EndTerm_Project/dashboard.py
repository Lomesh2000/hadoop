# ============================================================
# PIPELINE
# ============================================================

if run_button:

    # --------------------------------------------------------
    # Validate input
    # --------------------------------------------------------

    input_file = Path(input_path)

    if not input_file.exists():
        st.error(
            f"Input file not found:\n\n{input_file}"
        )
        st.stop()

    # --------------------------------------------------------
    # Command
    # --------------------------------------------------------

    command = [
        sys.executable,
        "-u",  # IMPORTANT: unbuffered stdout
        str(ORCHESTRATOR),
        "--input",
        str(input_file),
        "--output-dir",
        str(ROOT),
        "--mode",
        mode,
        "--top-n",
        str(top_n),
    ]

    env = os.environ.copy()

    # --------------------------------------------------------
    # Live UI placeholders
    # --------------------------------------------------------

    st.markdown("---")

    status_placeholder = st.empty()
    metric_placeholder = st.empty()
    current_line_placeholder = st.empty()

    # Result containers remain on screen
    q1_container = st.container()
    q2_container = st.container()
    q3_container = st.container()

    dq_container = st.container()
    final_container = st.container()

    # --------------------------------------------------------
    # Start pipeline
    # --------------------------------------------------------

    pipeline_start = time.perf_counter()

    try:
        process = subprocess.Popen(
            command,
            cwd=ROOT,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            env=env,
        )

    except Exception as exc:
        status_placeholder.error(
            f"❌ Failed to start pipeline: {exc}"
        )
        st.stop()

    # --------------------------------------------------------
    # Background reader
    # --------------------------------------------------------

    output_queue = queue.Queue()

    reader = threading.Thread(
        target=read_process_output,
        args=(process, output_queue),
        daemon=True,
    )

    reader.start()

    # --------------------------------------------------------
    # State
    # --------------------------------------------------------

    all_logs = []

    current_stage = None
    current_stage_start = pipeline_start

    current_job = None

    q1_shown = False
    q2_shown = False
    q3_shown = False

    dq_shown = False
    eof_received = False

    input_records = None
    valid_records = None
    malformed_records = None

    q1_time = None
    q2_time = None
    q3_time = None

    final_reported_time = None

    # --------------------------------------------------------
    # Live loop
    # --------------------------------------------------------

    while True:

        # --------------------------------------------
        # Consume available lines
        # --------------------------------------------

        while True:

            try:
                msg_type, value = (
                    output_queue.get_nowait()
                )

            except queue.Empty:
                break

            if msg_type == "line":

                line = value
                all_logs.append(line)

                # ------------------------------------
                # Detect stages
                # ------------------------------------

                if "STAGE 1:" in line:

                    current_stage = "stage1"
                    current_stage_start = time.perf_counter()

                elif (
                    "Submitting Hadoop Job Q1" in line
                    or "Executing Local Job Q1" in line
                ):

                    current_stage = "q1"
                    current_job = "Q1"
                    current_stage_start = time.perf_counter()

                elif (
                    "Submitting Hadoop Job Q2" in line
                    or "Executing Local Job Q2" in line
                ):

                    current_stage = "q2"
                    current_job = "Q2"
                    current_stage_start = time.perf_counter()

                elif (
                    "Submitting Hadoop Job Q3" in line
                    or "Executing Local Job Q3" in line
                ):

                    current_stage = "q3"
                    current_job = "Q3"
                    current_stage_start = time.perf_counter()

                elif "STAGE 3:" in line:

                    current_stage = "stage3"
                    current_job = None
                    current_stage_start = time.perf_counter()

                elif "STAGE 4:" in line:

                    current_stage = "stage4"
                    current_job = None
                    current_stage_start = time.perf_counter()

                elif "STAGE 5:" in line:

                    current_stage = "stage5"
                    current_job = None
                    current_stage_start = time.perf_counter()

                # ------------------------------------
                # Record counts
                # ------------------------------------

                parsed = parse_int(
                    line,
                    r"Total Ingested Records:\s*([\d,]+)",
                )

                if parsed is not None:
                    input_records = parsed

                parsed = parse_int(
                    line,
                    r"Valid Structured Lines:\s*([\d,]+)",
                )

                if parsed is not None:
                    valid_records = parsed

                parsed = parse_int(
                    line,
                    r"Malformed / Skipped:\s*([\d,]+)",
                )

                if parsed is not None:
                    malformed_records = parsed

                # ------------------------------------
                # Job completion
                # ------------------------------------

                if (
                    "Status: SUCCESS" in line
                    and current_job is not None
                ):

                    elapsed = parse_time(line)

                    if elapsed is not None:

                        if (
                            current_job == "Q1"
                            and not q1_shown
                        ):

                            q1_shown = True
                            q1_time = elapsed

                            with q1_container:

                                st.success(
                                    f"✅ Q1 completed in "
                                    f"{elapsed:.3f}s"
                                )

                                df = read_job_output(
                                    "Q1",
                                    top_n,
                                )

                                if df is not None:
                                    render_q1(df)

                                else:
                                    st.warning(
                                        "Q1 completed but "
                                        "output could not be read."
                                    )

                        elif (
                            current_job == "Q2"
                            and not q2_shown
                        ):

                            q2_shown = True
                            q2_time = elapsed

                            with q2_container:

                                st.success(
                                    f"✅ Q2 completed in "
                                    f"{elapsed:.3f}s"
                                )

                                df = read_job_output(
                                    "Q2",
                                    top_n,
                                )

                                if df is not None:
                                    render_q2(df)

                                else:
                                    st.warning(
                                        "Q2 completed but "
                                        "output could not be read."
                                    )

                        elif (
                            current_job == "Q3"
                            and not q3_shown
                        ):

                            q3_shown = True
                            q3_time = elapsed

                            with q3_container:

                                st.success(
                                    f"✅ Q3 completed in "
                                    f"{elapsed:.3f}s"
                                )

                                df = read_job_output(
                                    "Q3",
                                    top_n,
                                )

                                if df is not None:
                                    render_q3(df)

                                else:
                                    st.warning(
                                        "Q3 completed but "
                                        "output could not be read."
                                    )

                        current_job = None

                # ------------------------------------
                # DQ result
                # ------------------------------------

                if (
                    "OVERALL DATA QUALITY VERDICT:"
                    in line
                    and not dq_shown
                ):

                    dq_shown = True

                    with dq_container:

                        st.markdown(
                            "## ✅ Data Quality"
                        )

                        if "PASSED" in line:

                            st.success(
                                "All 7 data-quality checks passed."
                            )

                        else:

                            st.error(
                                "Data-quality validation failed."
                            )

                # ------------------------------------
                # Final runtime
                # ------------------------------------

                parsed_total = parse_total_time(
                    line
                )

                if parsed_total is not None:
                    final_reported_time = parsed_total

                # ------------------------------------
                # Latest log line
                # ------------------------------------

                current_line_placeholder.code(
                    line,
                    language="text",
                )

            elif msg_type == "error":

                current_line_placeholder.error(
                    value
                )

            elif msg_type == "eof":

                eof_received = True

        # --------------------------------------------
        # Live status
        # --------------------------------------------

        now = time.perf_counter()

        total_elapsed = (
            now - pipeline_start
        )

        current_elapsed = (
            now - current_stage_start
        )

        status_placeholder.info(
            f"🔵 **RUNNING**  |  "
            f"{stage_name(current_stage)}  |  "
            f"Stage elapsed: **{current_elapsed:.1f}s**  |  "
            f"Total elapsed: **{total_elapsed:.1f}s**"
        )

        # --------------------------------------------
        # Live metrics
        # --------------------------------------------

        metric_cols = metric_placeholder.columns(4)

        metric_cols[0].metric(
            "Input Records",
            (
                f"{input_records:,}"
                if input_records is not None
                else "Processing..."
            ),
        )

        metric_cols[1].metric(
            "Valid",
            (
                f"{valid_records:,}"
                if valid_records is not None
                else "Processing..."
            ),
        )

        metric_cols[2].metric(
            "Malformed",
            (
                f"{malformed_records:,}"
                if malformed_records is not None
                else "Processing..."
            ),
        )

        metric_cols[3].metric(
            "Elapsed",
            f"{total_elapsed:.1f}s",
        )

        # --------------------------------------------
        # End condition
        # --------------------------------------------

        if (
            eof_received
            and process.poll() is not None
            and output_queue.empty()
        ):
            break

        time.sleep(0.25)

    # ========================================================
    # PROCESS COMPLETE
    # ========================================================

    return_code = process.wait()

    total_elapsed = (
        time.perf_counter()
        - pipeline_start
    )

    with final_container:

        st.markdown("---")

        st.markdown(
            "## 🏁 Pipeline Status"
        )

        if return_code == 0:

            status_placeholder.success(
                f"🟢 **COMPLETED SUCCESSFULLY**  |  "
                f"Total time: **{total_elapsed:.2f}s**"
            )

        else:

            status_placeholder.error(
                f"🔴 **PIPELINE FAILED**  |  "
                f"Exit code: {return_code}  |  "
                f"Time: **{total_elapsed:.2f}s**"
            )

    # ========================================================
    # FINAL PERFORMANCE SUMMARY
    # ========================================================

    st.markdown(
        "## 📊 Performance Summary"
    )

    perf = st.columns(4)

    perf[0].metric(
        "Q1",
        (
            f"{q1_time:.2f}s"
            if q1_time is not None
            else "-"
        ),
    )

    perf[1].metric(
        "Q2",
        (
            f"{q2_time:.2f}s"
            if q2_time is not None
            else "-"
        ),
    )

    perf[2].metric(
        "Q3",
        (
            f"{q3_time:.2f}s"
            if q3_time is not None
            else "-"
        ),
    )

    perf[3].metric(
        "Full Pipeline",
        (
            f"{final_reported_time:.2f}s"
            if final_reported_time is not None
            else f"{total_elapsed:.2f}s"
        ),
    )

    # --------------------------------------------------------
    # Final timing table
    # --------------------------------------------------------

    timing_rows = []

    if q1_time is not None:
        timing_rows.append(
            {
                "Job": "Q1",
                "Reducers": reducers["q1"],
                "Time (s)": round(q1_time, 3),
            }
        )

    if q2_time is not None:
        timing_rows.append(
            {
                "Job": "Q2",
                "Reducers": reducers["q2"],
                "Time (s)": round(q2_time, 3),
            }
        )

    if q3_time is not None:
        timing_rows.append(
            {
                "Job": "Q3",
                "Reducers": reducers["q3"],
                "Time (s)": round(q3_time, 3),
            }
        )

    if timing_rows:

        timing_df = pd.DataFrame(
            timing_rows
        )

        st.dataframe(
            timing_df,
            use_container_width=True,
            hide_index=True,
        )

        fig = px.bar(
            timing_df,
            x="Job",
            y="Time (s)",
            text="Time (s)",
            title="MapReduce Job Runtime",
        )

        st.plotly_chart(
            fig,
            use_container_width=True,
        )

    # ========================================================
