# SUBPROCESS READER
# ============================================================

def read_process_output(process, output_queue):
    try:
        for line in iter(process.stdout.readline, ""):
            if not line:
                break

            output_queue.put(
                ("line", line.rstrip())
            )

    except Exception as exc:
        output_queue.put(
            ("error", str(exc))
        )

    finally:
        output_queue.put(
            ("eof", None)
        )


